-- GIU on the Move: seat availability and announcements from the transportation office
-- For a project that is ALREADY set up. Paste this file into the Supabase SQL Editor and click Run once.

-- Seat availability: the driver taps how full the bus is during a trip
alter table public.trip_runs add column if not exists occupancy text
    check (occupancy in ('seats', 'few', 'full'));
alter table public.trip_runs add column if not exists occupancy_at timestamp;

-- Announcements: short messages from the transportation office to riders
create table if not exists public.announcements (
    id         integer generated by default as identity primary key,
    message    text      not null check (char_length(message) between 1 and 300),
    created_by integer   not null references public.users (id),   -- the administrator
    created_at timestamp not null,
    ended_at   timestamp                                          -- set when the office takes it down
);

alter table public.announcements enable row level security;
