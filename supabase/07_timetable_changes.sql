-- GIU on the Move: timetable changes for a date range (for example midterms or Ramadan)
-- For a project that is ALREADY set up. Paste this file into the Supabase SQL Editor and click Run once.
-- Nothing else is changed: the normal timetable stays in "trips", and a change only applies between its two dates.

create table if not exists public.schedule_changes (
    id         integer generated by default as identity primary key,
    trip_id    integer   not null references public.trips (id),
    new_time   time      not null,
    from_date  date      not null,
    to_date    date      not null,
    reason     text,
    created_by integer   not null references public.users (id),   -- the administrator
    created_at timestamp not null,
    check (from_date <= to_date)
);

create index if not exists idx_schedule_changes_trip on public.schedule_changes (trip_id, from_date, to_date);

-- Same rule as every other table: row level security on, no policies (only the backend reads it)
alter table public.schedule_changes enable row level security;
