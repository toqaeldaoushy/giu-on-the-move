-- STEP 1 of 4. Paste this whole file into the Supabase SQL Editor and click Run.
--
-- Notes
--  * Same 12 tables as the SQLite version. Passwords are not stored here: Supabase Auth will handle logins,
--    and users.auth_user_id will link a row to its login later.
--  * Times are local Cairo time without a time zone (timestamp), exactly as in the simulated data.
--  * Row level security (RLS) is ON for every table and there are no policies yet. That means the public API
--    cannot read or write anything until we add rules for each role. The dashboard and the backend (which uses
--    the service role key) are not affected.

create table public.users (
    id           integer generated by default as identity primary key,
    name         text    not null,
    role         text    not null check (role in ('rider', 'driver', 'admin')),
    username     text    not null unique,
    phone        text,                                   -- placeholder numbers only
    share_phone  boolean not null default false,
    auth_user_id uuid    unique                          -- later: link to the Supabase Auth login
);

create table public.buses (
    id         integer generated by default as identity primary key,
    bus_number text    not null unique,
    plate      text    not null unique,
    capacity   integer not null check (capacity > 0),
    status     text    not null check (status in ('active', 'maintenance')),
    device_id  text    not null unique                   -- the phone installed on this bus
);

create table public.routes (
    id   integer generated by default as identity primary key,
    name text not null
);

create table public.route_points (                       -- the path, listed in the inbound direction
    route_id integer          not null references public.routes (id),
    seq      integer          not null,
    lat      double precision not null,
    lon      double precision not null,
    primary key (route_id, seq)
);

create table public.stops (
    id       integer generated by default as identity primary key,
    route_id integer          not null references public.routes (id),
    name     text             not null,
    lat      double precision not null,
    lon      double precision not null,
    seq      integer          not null,
    unique (route_id, seq)
);

create table public.trips (                              -- the timetable (the real one)
    id             integer generated by default as identity primary key,
    code           text    not null unique,
    label          text    not null,
    route_id       integer not null references public.routes (id),
    direction      text    not null check (direction in ('inbound', 'outbound')),
    scheduled_time time    not null
);

create table public.trip_runs (                          -- one trip on one day; the admin assigns bus and driver here
    id           integer generated by default as identity primary key,
    trip_id      integer not null references public.trips (id),
    run_date     date    not null,
    bus_id       integer references public.buses (id),
    driver_id    integer references public.users (id),  -- must be a user with role 'driver'
    status       text    not null check (status in ('scheduled', 'in_progress', 'completed', 'cancelled')),
    actual_start timestamp,
    actual_end   timestamp,
    unique (trip_id, run_date)
);

create table public.gps_pings (
    id          bigint generated by default as identity primary key,
    trip_run_id integer          not null references public.trip_runs (id),
    bus_id      integer          not null references public.buses (id),
    device_id   text             not null,
    timestamp   timestamp        not null,
    lat         double precision not null,
    lon         double precision not null,
    speed_kmh   double precision not null check (speed_kmh >= 0),
    unique (trip_run_id, timestamp)
);

create table public.problem_reports (                    -- reported by the driver
    id          integer generated by default as identity primary key,
    trip_run_id integer   not null references public.trip_runs (id),
    driver_id   integer   not null references public.users (id),
    report_type text      not null check (report_type in ('traffic_delay', 'breakdown', 'bus_full', 'other')),
    note        text,
    created_at  timestamp not null
);

create table public.assignment_changes (                 -- audit trail of admin re-assignments
    id            integer generated by default as identity primary key,
    trip_run_id   integer   not null references public.trip_runs (id),
    old_driver_id integer references public.users (id),
    new_driver_id integer references public.users (id),
    old_bus_id    integer references public.buses (id),
    new_bus_id    integer references public.buses (id),
    changed_by    integer   not null references public.users (id),   -- must be the admin
    reason        text,
    changed_at    timestamp not null
);

create table public.alerts (                             -- a rider asks to be notified before a trip
    id             integer generated by default as identity primary key,
    user_id        integer   not null references public.users (id),
    trip_run_id    integer   not null references public.trip_runs (id),
    stop_id        integer   not null references public.stops (id),
    minutes_before integer   not null check (minutes_before in (2, 5, 10)),
    created_at     timestamp not null
);

create table public.rider_reports (                      -- "the bus was full" reports from riders
    id          integer generated by default as identity primary key,
    user_id     integer   not null references public.users (id),
    trip_run_id integer   not null references public.trip_runs (id),
    report_type text      not null check (report_type in ('bus_full')),
    created_at  timestamp not null
);

create index idx_gps_pings_run_time on public.gps_pings (trip_run_id, timestamp);

-- Row level security: on for every table, no policies yet (the public API is closed).
alter table public.users              enable row level security;
alter table public.buses              enable row level security;
alter table public.routes             enable row level security;
alter table public.route_points       enable row level security;
alter table public.stops              enable row level security;
alter table public.trips              enable row level security;
alter table public.trip_runs          enable row level security;
alter table public.gps_pings          enable row level security;
alter table public.problem_reports    enable row level security;
alter table public.assignment_changes enable row level security;
alter table public.alerts             enable row level security;
alter table public.rider_reports      enable row level security;
