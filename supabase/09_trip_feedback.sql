-- GIU on the Move: riders rate a finished trip (1 to 5 stars and an optional comment)
-- For a project that is ALREADY set up. Paste this file into the Supabase SQL Editor and click Run once.

create table if not exists public.trip_feedback (
    id          integer generated by default as identity primary key,
    user_id     integer   not null references public.users (id),
    trip_run_id integer   not null references public.trip_runs (id),
    rating      integer   not null check (rating between 1 and 5),
    comment     text      check (char_length(comment) <= 300),
    created_at  timestamp not null,
    unique (user_id, trip_run_id)                      -- one rating per rider and trip (it can be changed)
);

alter table public.trip_feedback enable row level security;
